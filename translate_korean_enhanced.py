def has_korean_text(text: str) -> bool:
    """检查文本是否包含韩语字符"""
    if not isinstance(text, str):
        return False
    return bool(re.search(r'[가-힣]', text))

def translate_korean_text(text: str) -> str:
    """翻译韩语文本为简体中文"""
    if not isinstance(text, str) or not has_korean_text(text):
        return text
    
    translated = text
    
    # 按长度排序，优先匹配长词组
    sorted_terms = sorted(KOREAN_TO_CHINESE.items(), key=lambda x: len(x[0]), reverse=True)
    
    for korean, chinese in sorted_terms:
        if korean in translated:
            translated = translated.replace(korean, chinese)
    
    # 清理多余的空格
    translated = re.sub(r'\s+', ' ', translated).strip()
    
    return translated

def process_json_value(value: Any) -> Any:
    """递归处理JSON值，只翻译str字段中的韩语文本"""
    if isinstance(value, dict):
        result = {}
        for k, v in value.items():
            if k == 'str' and isinstance(v, str):
                # 只翻译str字段
                result[k] = translate_korean_text(v)
            else:
                result[k] = process_json_value(v)
        return result
    elif isinstance(value, list):
        return [process_json_value(item) for item in value]
    else:
        return value

def translate_json_file(file_path: str) -> bool:
    """翻译单个JSON文件"""
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        # 检查是否有韩语文本需要翻译
        original_str = json.dumps(data, ensure_ascii=False)
        if not has_korean_text(original_str):
            return False
        
        # 翻译数据
        translated_data = process_json_value(data)
        
        # 保存翻译后的文件
        with open(file_path, 'w', encoding='utf-8') as f:
            json.dump(translated_data, f, ensure_ascii=False, indent=2)
        
        return True
        
    except Exception as e:
        print(f"处理文件 {file_path} 时出错: {e}")
        return False

def main():
    """主函数"""
    export_dir = '/Users/bytedance/work/project/pokemon-simple-chinese/simp_chinese_Export'
    
    if not os.path.exists(export_dir):
        print(f"目录不存在: {export_dir}")
        return
    
    print("开始翻译韩语文本...")
    
    total_files = 0
    modified_files = 0
    error_files = 0
    
    for filename in os.listdir(export_dir):
        if filename.endswith('.json'):
            file_path = os.path.join(export_dir, filename)
            total_files += 1
            
            try:
                if translate_json_file(file_path):
                    modified_files += 1
                    print(f"已翻译: {filename}")
            except Exception as e:
                error_files += 1
                print(f"错误: {filename} - {e}")
    
    print(f"\n翻译完成！")
    print(f"总文件数: {total_files}")
    print(f"修改文件数: {modified_files}")
    print(f"错误文件数: {error_files}")
    print(f"无需修改: {total_files - modified_files - error_files}")

if __name__ == '__main__':
    main()